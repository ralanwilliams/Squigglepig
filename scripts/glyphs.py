"""Take what the props' text needs from Roboto Bold (the app's bold font),
written to src/theme/skins/glyphs.ts:

  - each character's width, so words in a prop's text slot (a speech bubble,
    a name on a cake: props.ts, SkinDecor.tsx PropArt) are shrunk to fit by
    what they really measure, not an average letter's width: a line of wide
    letters would otherwise run out of its bubble;
  - the digits 0 to 9 as outlines, so a number (Ash's jersey) is plain shapes
    with no font behind it. Text in an SVG is drawn with whatever font the
    moment finds: the light / dark sweep's photo of the screen can fall back
    to a regular one, and the number briefly changes weight. Shapes look the
    same everywhere, always.

Run from the repo root after changing the font:

    python scripts/glyphs.py

Needs fonttools (pip install fonttools): only a tool to read the font, it
ships nothing in the app. Roboto is under the Apache License 2.0, credited
on the licenses screen with the font itself.
"""
from pathlib import Path

from fontTools.pens.svgPathPen import SVGPathPen
from fontTools.ttLib import TTFont

ROOT = Path(__file__).resolve().parent.parent
FONT = ROOT / 'node_modules' / '@expo-google-fonts' / 'roboto' / '700Bold' / 'Roboto_700Bold.ttf'
OUT = ROOT / 'src' / 'theme' / 'skins' / 'glyphs.ts'
# The characters measured: printable ASCII and Latin-1 (accented letters,
# curly quotes and the like). Anything else (an emoji) is taken as WIDE.
CHARS = [chr(c) for c in range(32, 127)] + [chr(c) for c in range(160, 256)] + list('‘’“”…–—€')


def main():
    font = TTFont(FONT)
    upm = font['head'].unitsPerEm
    cmap = font.getBestCmap()
    glyphs = font.getGlyphSet()
    widths = []
    for ch in CHARS:
        name = cmap.get(ord(ch))
        if name:
            key = ch.replace('\\', '\\\\').replace("'", "\\'")
            widths.append(f"'{key}': {round(glyphs[name].width / upm, 3)}")
    digits = []
    for ch in '0123456789':
        name = cmap[ord(ch)]
        pen = SVGPathPen(glyphs, lambda v: str(round(v)))
        glyphs[name].draw(pen)
        digits.append(f"  '{ch}': {{ advance: {glyphs[name].width}, d: '{pen.getCommands()}' }},")
    rows = [', '.join(widths[i:i + 12]) for i in range(0, len(widths), 12)]
    OUT.write_text('\n'.join([
        '// Generated by scripts/glyphs.py from Roboto Bold — do not edit.',
        '',
        "// Each character's width, in ems (SkinDecor.tsx fits a text slot's words",
        '// by it). A character not here (an emoji) is taken as WIDE.',
        'export const WIDTHS: Record<string, number> = {',
        *[f'  {r},' for r in rows],
        '};',
        'export const WIDE = 1.15;',
        '',
        '// How wide a line of text is in Roboto Bold, in ems.',
        'export const emWidth = (line: string) => [...line].reduce((w, c) => w + (WIDTHS[c] ?? WIDE), 0);',
        '',
        "// The digits as outlines, in the font's own units (y up, the baseline at 0),",
        '// for a number drawn in a prop without a font (SkinDecor.tsx PropArt).',
        f'export const DIGIT_EM = {upm};',
        'export const DIGITS: Record<string, { advance: number; d: string }> = {',
        *digits,
        '};',
        '',
    ]), encoding='utf-8', newline='\n')
    print(f'wrote {OUT.relative_to(ROOT)}: {len(widths)} widths, 10 digits')


if __name__ == '__main__':
    main()
