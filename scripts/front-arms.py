"""Trace the pig's forearm on the viewer's left, in the art's own colours, so
something carried across his belly (a long gun: layout.ts carried) can go
behind it. A hoof drawn again on its own is a flat black shape that sinks
into a dark gun; the whole forearm, pink, shading, outline and hoof, reads
as in front of it.

Writes src/theme/skins/frontArms.ts: the props (spread into props.ts PROPS)
and where each goes on its piece of art (layout.ts FRONT_ARMS). Run from
the repo root after changing any of the pig artwork or anything here:

    python scripts/front-arms.py

Uses the tracing in scripts/ash-wear.py. Needs numpy and Pillow (pip
install numpy pillow).
"""
import importlib.util
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
OUT = ROOT / 'src' / 'theme' / 'skins' / 'frontArms.ts'

sys.dont_write_bytecode = True  # no __pycache__ left in scripts/
spec = importlib.util.spec_from_file_location('ash_wear', Path(__file__).resolve().parent / 'ash-wear.py')
aw = importlib.util.module_from_spec(spec)
spec.loader.exec_module(aw)

# The box round the forearm on the viewer's left, as fractions of the image
# (the same as the arm Ash's crutch is held in, scripts/ash-wear.py), on each
# piece of art a long gun is carried on.
ARMS = {
    'Still': dict(file='squigglepig_clear.png', box=(0.11, 0.53, 0.215, 0.725)),
    'Winner': dict(file='squigglepig_winner.gif', box=(0.1, 0.52, 0.215, 0.725)),
    'Waiting': dict(file='squigglepig.gif', box=(0.33, 0.64, 0.42, 0.8)),
}


# How dark a pixel just outside the arm has to be to count as the soft edge
# of its outline (0 black, 255 white): the body's pink is far lighter.
EDGE = 150


def trace(cfg):
    im = aw.load(cfg['file'])
    H, W = im.shape[:2]
    solid = im[..., 3] > 128
    # The arm inside its outline, and the soft dark edge of that outline just
    # outside it, but none of the body's pink beyond: that would show as a
    # pink fringe over the gun.
    inside = aw.arm(im, cfg['box'], aw.REACH)
    m = (inside | (aw.dilate(inside, 2) & (aw.lum(im) < EDGE))) & solid
    frame, size = aw.frame_of(m)
    k = frame[2]
    # The outline and the hoof in solid black, over the arm's own colours: the
    # soft edge of a small piece of art would otherwise come out as specks of
    # dark red and brown.
    line = m & (aw.lum(im) < EDGE)
    layers = aw.posterize(im, m & ~line) + [(line, '#000000')]
    prop = {'rim': False, 'w': 100, 'h': round(size[1] * k, 1), 'anchor': [50, round(size[1] * k / 2, 1)],
            'shapes': [{'d': aw.path(layer, frame), 'fill': fill} for layer, fill in layers]}
    return prop, aw.placement(frame, size, (H, W))


def main():
    props, places = [], []
    for name, cfg in ARMS.items():
        prop, place = trace(cfg)
        props.append(f'  hoofArm{name}: {aw.ts(prop)},')
        places.append((name, place))
    lines = [
        '// Generated by scripts/front-arms.py from the pig artwork — do not edit.',
        "// The pig's forearm on the viewer's left, hoof and all, in the art's own",
        '// colours, drawn again over a long gun carried across his belly (layout.ts',
        "// carried), so the gun goes behind it. Rerun the script after changing the art.",
        "import type { Prop } from './props';",
        '',
        'export const FRONT_ARM_PROPS = {',
        *props,
        '} satisfies Record<string, Prop>;',
        '',
        '// Where each goes on its piece of art.',
        "export const FRONT_ARM_AT = {",
        *[f"  {n}: {{ x: {p['x']}, y: {p['y']}, w: {p['w']} }}," for n, p in places],
        '};',
        '',
    ]
    OUT.write_text('\n'.join(lines), encoding='utf-8', newline='\n')
    print(f'wrote {OUT.relative_to(ROOT)}')


if __name__ == '__main__':
    main()
